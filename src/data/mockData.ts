// ===== Helper: Agrupar proyectos por fecha =====

export function getProyectosPorFecha(): { fecha: string; proyectos: ProyectoLey[] }[] {
  const grouped = new Map<string, ProyectoLey[]>();

  for (const p of proyectos) {
    const existing = grouped.get(p.fechaIngreso) || [];
    existing.push(p);
    grouped.set(p.fechaIngreso, existing);
  }

  return Array.from(grouped.entries())
    .sort((a, b) => b[0].localeCompare(a[0]))
    .map(([fecha, proyectos]) => ({ fecha, proyectos }));
}

